#!/usr/bin/env python3
"""
god-generate-yaml.py - regenerates god_hosts_linux.yaml + god_mode.yaml
from /data/options.json (the addon hosts list). Native HA cards only
(no HACS dependency). Idempotent.
"""
import json
import os
import sys

OPTIONS = "/data/options.json"
OUT_PKG_DIR = "/usr/share/god-mode/lovelace/packages"
OUT_DASH_DIR = "/usr/share/god-mode/lovelace/dashboards"
PKG_FILE = os.path.join(OUT_PKG_DIR, "god_hosts_linux.yaml")
DASH_FILE = os.path.join(OUT_DASH_DIR, "god_mode.yaml")

METRICS = [
    ("cpu",          "cpu_pct",            "%",   "mdi:cpu-64-bit"),
    ("mem",          "mem_pct",            "%",   "mdi:memory"),
    ("swap",         "swap_pct",           "%",   "mdi:swap-horizontal"),
    ("disk",         "disk_max_pct",       "%",   "mdi:harddisk"),
    ("temp",         "temp_max_c",         "°C",  "mdi:thermometer"),
    ("load",         "load_1m",            None,  "mdi:gauge"),
    ("updates",      "updates_pending",    None,  "mdi:package-up"),
    ("uptime",       "uptime_s",           "s",   "mdi:clock-outline"),
    ("smart_temp",   "smart_temp_max",     "°C",  "mdi:thermometer-alert"),
    ("smart_failed", "smart_failed_disks", None,  "mdi:harddisk-remove"),
]

CATEGORY_LABELS = {
    "pve_node":      ("Proxmox cluster", "mdi:server-network"),
    "server":        ("Linux servers",   "mdi:server"),
    "sbc":           ("SBCs",            "mdi:raspberry-pi"),
    "desktop_linux": ("Linux desktops",  "mdi:linux"),
    "desktop_win":   ("Windows",         "mdi:microsoft-windows"),
    "desktop_mac":   ("macOS",           "mdi:apple"),
    "network":       ("Network",         "mdi:router-network"),
}


def load_hosts():
    try:
        with open(OPTIONS) as f:
            opts = json.load(f)
        return opts.get("hosts", [])
    except Exception as e:
        print(f"[gen] failed reading {OPTIONS}: {e}", file=sys.stderr)
        return []


def gen_package(hosts):
    lines = [
        "# AUTO-GENERATED - do not edit. Regenerated by god-generate-yaml.py",
        f"# Hosts: {len(hosts)}",
        "rest:",
        "  - resource: http://172.30.32.1:9876/api/hosts",
        "    scan_interval: 60",
        "    sensor:",
    ]
    for h in hosts:
        name = h["name"]
        for metric_name, json_key, unit, icon in METRICS:
            lines.append(f'      - name: "god_host_{name}_{metric_name}"')
            lines.append(f"        unique_id: god_host_{name}_{metric_name}")
            lines.append(
                f'        value_template: "{{{{ value_json.{name}.{json_key} | default(0) }}}}"'
            )
            if unit:
                lines.append(f'        unit_of_measurement: "{unit}"')
            lines.append(f"        icon: {icon}")
        # smart_health (string)
        lines.append(f'      - name: "god_host_{name}_smart_health"')
        lines.append(f"        unique_id: god_host_{name}_smart_health")
        lines.append(
            f"        value_template: \"{{{{ value_json.{name}.smart_health | default('unknown') }}}}\""
        )
        lines.append("        icon: mdi:harddisk")
        # os (string)
        lines.append(f'      - name: "god_host_{name}_os"')
        lines.append(f"        unique_id: god_host_{name}_os")
        lines.append(
            f"        value_template: \"{{{{ value_json.{name}._god_os | default('unknown') }}}}\""
        )
        lines.append("        icon: mdi:laptop")
        # online binary
        lines.append(f'      - name: "god_host_{name}_online"')
        lines.append(f"        unique_id: god_host_{name}_online")
        lines.append(
            f"        value_template: \"{{{{ 'on' if (value_json.{name}.ts | default(0) | int) > 0 else 'off' }}}}\""
        )
        lines.append("        icon: mdi:lan-connect")

    # template binary_sensors for online + category attribute
    lines.append("")
    lines.append("template:")
    lines.append("  - binary_sensor:")
    for h in hosts:
        name = h["name"]
        cat = h.get("category", "server")
        addr = h.get("addr", "")
        lines.append(f'      - name: "god_host_{name}_online"')
        lines.append(f"        unique_id: god_host_{name}_online_bin")
        lines.append(f"        device_class: connectivity")
        lines.append(
            f"        state: \"{{{{ states('sensor.god_host_{name}_online') == 'on' }}}}\""
        )
        lines.append(f"        attributes:")
        lines.append(f'          category: "{cat}"')
        lines.append(f'          addr: "{addr}"')
        lines.append(f'          friendly_label: "{name}"')

    # aggregated counters (warning/critical)
    lines.append("")
    lines.append("  - sensor:")
    lines.append('      - name: "god_alerts_warning_count"')
    lines.append("        unique_id: god_alerts_warning_count")
    lines.append("        state: >")
    lines.append("          {% set n = namespace(c=0) %}")
    for h in hosts:
        name = h["name"]
        lines.append(
            f"          {{% set cpu = states('sensor.god_host_{name}_cpu') | float(0) %}}"
        )
        lines.append(
            f"          {{% set mem = states('sensor.god_host_{name}_mem') | float(0) %}}"
        )
        lines.append(
            f"          {{% set sw  = states('sensor.god_host_{name}_swap') | float(0) %}}"
        )
        lines.append(
            f"          {{% set dk  = states('sensor.god_host_{name}_disk') | float(0) %}}"
        )
        lines.append(
            f"          {{% set tp  = states('sensor.god_host_{name}_temp') | float(0) %}}"
        )
        lines.append(
            f"          {{% set st  = states('sensor.god_host_{name}_smart_temp') | float(0) %}}"
        )
        lines.append(
            "          {% if cpu>80 or mem>85 or sw>50 or dk>85 or tp>75 or st>55 %}{% set n.c = n.c + 1 %}{% endif %}"
        )
    lines.append("          {{ n.c }}")

    lines.append('      - name: "god_alerts_critical_count"')
    lines.append("        unique_id: god_alerts_critical_count")
    lines.append("        state: >")
    lines.append("          {% set n = namespace(c=0) %}")
    for h in hosts:
        name = h["name"]
        lines.append(
            f"          {{% set cpu = states('sensor.god_host_{name}_cpu') | float(0) %}}"
        )
        lines.append(
            f"          {{% set mem = states('sensor.god_host_{name}_mem') | float(0) %}}"
        )
        lines.append(
            f"          {{% set sw  = states('sensor.god_host_{name}_swap') | float(0) %}}"
        )
        lines.append(
            f"          {{% set dk  = states('sensor.god_host_{name}_disk') | float(0) %}}"
        )
        lines.append(
            f"          {{% set tp  = states('sensor.god_host_{name}_temp') | float(0) %}}"
        )
        lines.append(
            f"          {{% set st  = states('sensor.god_host_{name}_smart_temp') | float(0) %}}"
        )
        lines.append(
            f"          {{% set sh  = states('sensor.god_host_{name}_smart_health') %}}"
        )
        lines.append(
            "          {% if cpu>95 or mem>95 or sw>80 or dk>95 or tp>85 or st>65 or sh in ['FAILED','FAIL'] %}{% set n.c = n.c + 1 %}{% endif %}"
        )
    lines.append("          {{ n.c }}")

    lines.append('      - name: "god_hosts_online_count"')
    lines.append("        unique_id: god_hosts_online_count")
    lines.append("        state: >")
    lines.append(f"          {{% set total = {len(hosts)} %}}")
    lines.append("          {% set n = namespace(c=0) %}")
    for h in hosts:
        name = h["name"]
        lines.append(
            f"          {{% if is_state('binary_sensor.god_host_{name}_online', 'on') %}}{{% set n.c = n.c + 1 %}}{{% endif %}}"
        )
    lines.append("          {{ n.c }}")
    lines.append('        attributes:')
    lines.append(f'          total: {len(hosts)}')

    return "\n".join(lines) + "\n"


def hosts_in(cat, hosts):
    return [h for h in hosts if h.get("category") == cat]


def gauge_card(entity, name, severity_green, severity_yellow, severity_red, unit="%"):
    return [
        "      - type: gauge",
        f"        entity: {entity}",
        f'        name: "{name}"',
        f'        unit: "{unit}"',
        "        min: 0",
        "        max: 100",
        "        severity:",
        f"          green: {severity_green}",
        f"          yellow: {severity_yellow}",
        f"          red: {severity_red}",
        "        needle: true",
    ]


def gen_dashboard(hosts):
    lines = [
        "# AUTO-GENERATED - do not edit. Regenerated by god-generate-yaml.py",
        "# 100% native HA cards. No HACS required.",
        "title: GOD Mode",
        "views:",
        "",
        "  # ============ OVERVIEW ============",
        "  - title: Overview",
        "    path: overview",
        "    icon: mdi:eye-outline",
        "    type: sections",
        "    max_columns: 3",
        "    sections:",
        "      - type: grid",
        "        cards:",
        "          - type: markdown",
        "            content: |",
        "              # GOD Mode",
        f"              _Monitoring {len(hosts)} hosts · auto-refresh 60s_",
        "          - type: glance",
        '            title: "Resumen"',
        "            columns: 3",
        "            entities:",
        "              - entity: sensor.god_hosts_online_count",
        '                name: "Online"',
        "              - entity: sensor.god_alerts_warning_count",
        '                name: "Warning"',
        "              - entity: sensor.god_alerts_critical_count",
        '                name: "Critical"',
        "          - type: glance",
        '            title: "Hosts online"',
        "            columns: 5",
        "            show_state: false",
        "            show_icon: true",
        "            entities:",
    ]
    for h in hosts:
        lines.append(f"              - entity: binary_sensor.god_host_{h['name']}_online")
        lines.append(f'                name: "{h["name"]}"')

    # Comparison graphs: explicit entity list per metric
    def comparison_graph(metric_name, title, hours=6):
        out = [
            "      - type: grid",
            "        cards:",
            "          - type: history-graph",
            f'            title: "{title}"',
            f"            hours_to_show: {hours}",
            "            refresh_interval: 60",
            "            entities:",
        ]
        for h in hosts:
            out.append(f"              - entity: sensor.god_host_{h['name']}_{metric_name}")
        return out

    lines.append("")
    lines += comparison_graph("cpu", "CPU comparado (%)", 6)
    lines += comparison_graph("mem", "Memoria comparada (%)", 6)
    lines += comparison_graph("swap", "Swap (%)", 12)
    lines += comparison_graph("disk", "Disco max (%)", 24)
    lines += comparison_graph("temp", "Temperatura (°C)", 12)
    lines += comparison_graph("smart_temp", "Temperatura SMART (°C)", 24)

    # SMART health table
    lines.append("      - type: grid")
    lines.append("        cards:")
    lines.append("          - type: entities")
    lines.append('            title: "SMART health"')
    lines.append("            entities:")
    for h in hosts:
        lines.append(f"              - entity: sensor.god_host_{h['name']}_smart_health")
        lines.append(f'                name: "{h["name"]}"')

    # ============ PER-CATEGORY VIEWS ============
    for cat, (label, icon) in CATEGORY_LABELS.items():
        cat_hosts = hosts_in(cat, hosts)
        if not cat_hosts:
            continue
        lines.append("")
        lines.append(f"  - title: {label}")
        lines.append(f"    path: {cat}")
        lines.append(f"    icon: {icon}")
        lines.append("    cards:")
        lines.append("      - type: markdown")
        lines.append(f'        content: "## {label} ({len(cat_hosts)} hosts)"')
        lines.append("      - type: glance")
        lines.append('        title: "Online"')
        lines.append("        columns: 4")
        lines.append("        show_state: false")
        lines.append("        entities:")
        for h in cat_hosts:
            lines.append(f"          - entity: binary_sensor.god_host_{h['name']}_online")
            lines.append(f'            name: "{h["name"]}"')
        for metric in ("cpu", "mem", "disk", "temp"):
            label_m = {"cpu": "CPU %", "mem": "RAM %", "disk": "Disco %", "temp": "Temp °C"}[metric]
            lines.append("      - type: history-graph")
            lines.append(f'        title: "{label_m}"')
            lines.append("        hours_to_show: 12")
            lines.append("        refresh_interval: 60")
            lines.append("        entities:")
            for h in cat_hosts:
                lines.append(f"          - entity: sensor.god_host_{h['name']}_{metric}")

    # ============ PER-HOST DETAIL VIEWS ============
    for h in hosts:
        name = h["name"]
        cat = h.get("category", "server")
        addr = h.get("addr", "")
        lines.append("")
        lines.append(f"  - title: {name}")
        lines.append(f"    path: host_{name}")
        lines.append("    icon: mdi:server")
        lines.append("    cards:")
        lines.append("      - type: markdown")
        lines.append(f'        content: "## {name} — `{addr}` · {cat}"')
        lines.append("      - type: glance")
        lines.append("        columns: 4")
        lines.append("        entities:")
        lines.append(f"          - entity: binary_sensor.god_host_{name}_online")
        lines.append('            name: Online')
        lines.append(f"          - entity: sensor.god_host_{name}_os")
        lines.append('            name: OS')
        lines.append(f"          - entity: sensor.god_host_{name}_uptime")
        lines.append('            name: Uptime')
        lines.append(f"          - entity: sensor.god_host_{name}_updates")
        lines.append('            name: Updates')
        # 4 gauges row
        lines.append("      - type: horizontal-stack")
        lines.append("        cards:")
        lines.append("          - type: gauge")
        lines.append(f"            entity: sensor.god_host_{name}_cpu")
        lines.append("            name: CPU")
        lines.append('            unit: "%"')
        lines.append("            min: 0")
        lines.append("            max: 100")
        lines.append("            severity: {green: 0, yellow: 70, red: 90}")
        lines.append("            needle: true")
        lines.append("          - type: gauge")
        lines.append(f"            entity: sensor.god_host_{name}_mem")
        lines.append("            name: RAM")
        lines.append('            unit: "%"')
        lines.append("            min: 0")
        lines.append("            max: 100")
        lines.append("            severity: {green: 0, yellow: 75, red: 90}")
        lines.append("            needle: true")
        lines.append("          - type: gauge")
        lines.append(f"            entity: sensor.god_host_{name}_disk")
        lines.append("            name: Disco")
        lines.append('            unit: "%"')
        lines.append("            min: 0")
        lines.append("            max: 100")
        lines.append("            severity: {green: 0, yellow: 80, red: 92}")
        lines.append("            needle: true")
        lines.append("          - type: gauge")
        lines.append(f"            entity: sensor.god_host_{name}_temp")
        lines.append("            name: Temp")
        lines.append('            unit: "°C"')
        lines.append("            min: 0")
        lines.append("            max: 100")
        lines.append("            severity: {green: 0, yellow: 65, red: 80}")
        lines.append("            needle: true")
        # SMART panel
        lines.append("      - type: entities")
        lines.append('        title: SMART / Disk')
        lines.append("        entities:")
        lines.append(f"          - entity: sensor.god_host_{name}_smart_health")
        lines.append(f"          - entity: sensor.god_host_{name}_smart_temp")
        lines.append(f"          - entity: sensor.god_host_{name}_smart_failed")
        lines.append(f"          - entity: sensor.god_host_{name}_swap")
        lines.append(f"          - entity: sensor.god_host_{name}_load")
        # History graphs
        lines.append("      - type: history-graph")
        lines.append('        title: CPU / RAM / Swap')
        lines.append("        hours_to_show: 24")
        lines.append("        entities:")
        lines.append(f"          - entity: sensor.god_host_{name}_cpu")
        lines.append(f"          - entity: sensor.god_host_{name}_mem")
        lines.append(f"          - entity: sensor.god_host_{name}_swap")
        lines.append("      - type: history-graph")
        lines.append('        title: Disco / Temp')
        lines.append("        hours_to_show: 24")
        lines.append("        entities:")
        lines.append(f"          - entity: sensor.god_host_{name}_disk")
        lines.append(f"          - entity: sensor.god_host_{name}_temp")
        lines.append(f"          - entity: sensor.god_host_{name}_smart_temp")

    # Config view
    lines.append("")
    lines.append("  - title: Config")
    lines.append("    path: config")
    lines.append("    icon: mdi:tune")
    lines.append("    cards:")
    lines.append("      - type: markdown")
    lines.append('        content: "## GOD Mode · Configuración"')
    lines.append("      - type: entities")
    lines.append('        title: Alertas')
    lines.append("        entities:")
    lines.append("          - input_select.god_alerts_enabled")
    lines.append("          - input_text.god_telegram_chat_id")
    lines.append("          - input_text.god_last_alert")
    lines.append("      - type: entities")
    lines.append('        title: Smoke test')
    lines.append("        entities:")
    lines.append("          - sensor.god_mode_loaded")

    return "\n".join(lines) + "\n"


def main():
    hosts = load_hosts()
    if not hosts:
        print("[gen] no hosts in options.json - aborting", file=sys.stderr)
        sys.exit(0)
    os.makedirs(OUT_PKG_DIR, exist_ok=True)
    os.makedirs(OUT_DASH_DIR, exist_ok=True)
    pkg = gen_package(hosts)
    dash = gen_dashboard(hosts)
    with open(PKG_FILE, "w") as f:
        f.write(pkg)
    with open(DASH_FILE, "w") as f:
        f.write(dash)
    print(f"[gen] wrote {PKG_FILE} ({len(pkg)} bytes)")
    print(f"[gen] wrote {DASH_FILE} ({len(dash)} bytes)")
    print(f"[gen] hosts: {len(hosts)}")


if __name__ == "__main__":
    main()
