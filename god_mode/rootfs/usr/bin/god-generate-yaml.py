#!/usr/bin/env python3
"""
god-generate-yaml.py - regenerates god_hosts_linux.yaml from
/data/options.json. From v0.4.0 we no longer generate a Lovelace
dashboard YAML: the rich UI lives in the addon's own ingress webui
(http://<ha>/api/hassio_ingress/<token>/), backed by /api/* endpoints
on god-collector. This script's job is reduced to exposing the bare
minimum to HA so the existing god_alerts.yaml package keeps firing:

  - Per host: binary_sensor.god_host_<name>_online
              sensor.god_host_<name>_cpu / _mem / _temp / _disk
  - Aggregates: sensor.god_hosts_online_count
                sensor.god_alerts_warning_count
                sensor.god_alerts_critical_count
                sensor.god_alerts_offline_count

Everything else (SMART, swap, load, updates, uptime, OS, per-host
history, sparklines, drill-down) is shown in the webui SPA instead
of HA, so we stop fighting Lovelace's templating limits.
"""
import json
import os
import sys

OPTIONS = "/data/options.json"
OUT_PKG_DIR = "/usr/share/god-mode/lovelace/packages"
PKG_FILE = os.path.join(OUT_PKG_DIR, "god_hosts_linux.yaml")

# Minimal per-host metrics surfaced to HA. The webui exposes the full
# set directly from the collector.
PER_HOST_METRICS = [
    ("cpu",  "cpu_pct",       "%",   "mdi:cpu-64-bit"),
    ("mem",  "mem_pct",       "%",   "mdi:memory"),
    ("disk", "disk_max_pct",  "%",   "mdi:harddisk"),
    ("temp", "temp_max_c",    "°C",  "mdi:thermometer"),
]


def load_hosts():
    try:
        with open(OPTIONS) as f:
            opts = json.load(f)
        return opts.get("hosts", [])
    except Exception as e:
        print(f"[gen] failed reading {OPTIONS}: {e}", file=sys.stderr)
        return []


def gen_package(hosts):
    lines = [
        "# AUTO-GENERATED - do not edit. Regenerated by god-generate-yaml.py",
        f"# Hosts: {len(hosts)} · minimal sensors set (v0.4.0+)",
        "# Rich monitoring UI lives in the addon's ingress webui, not Lovelace.",
        "rest:",
        "  - resource: http://172.30.32.1:9876/api/hosts",
        "    scan_interval: 60",
        "    sensor:",
    ]
    # Per-host minimal sensors
    for h in hosts:
        name = h["name"]
        for metric_name, json_key, unit, icon in PER_HOST_METRICS:
            lines.append(f'      - name: "god_host_{name}_{metric_name}"')
            lines.append(f"        unique_id: god_host_{name}_{metric_name}")
            lines.append(
                f'        value_template: "{{{{ value_json.{name}.{json_key} | default(0) }}}}"'
            )
            if unit:
                lines.append(f'        unit_of_measurement: "{unit}"')
            lines.append(f"        icon: {icon}")
        # online (state-only sensor, used by the binary_sensor below)
        lines.append(f'      - name: "god_host_{name}_online_raw"')
        lines.append(f"        unique_id: god_host_{name}_online_raw")
        lines.append(
            f"        value_template: \"{{{{ 'on' if (value_json.{name}.ts | default(0) | int) > 0 else 'off' }}}}\""
        )
        lines.append("        icon: mdi:lan-connect")

    # template binary_sensors for online + category attribute
    lines.append("")
    lines.append("template:")
    lines.append("  - binary_sensor:")
    for h in hosts:
        name = h["name"]
        cat = h.get("category", "server")
        addr = h.get("addr", "")
        parent = h.get("parent", "")
        lines.append(f'      - name: "god_host_{name}_online"')
        lines.append(f"        unique_id: god_host_{name}_online_bin")
        lines.append("        device_class: connectivity")
        lines.append(
            f"        state: \"{{{{ states('sensor.god_host_{name}_online_raw') == 'on' }}}}\""
        )
        lines.append("        attributes:")
        lines.append(f'          category: "{cat}"')
        lines.append(f'          addr: "{addr}"')
        if parent:
            lines.append(f'          parent: "{parent}"')
        lines.append(f'          friendly_label: "{name}"')

    # Aggregated counters
    lines.append("")
    lines.append("  - sensor:")
    # warning_count
    lines.append('      - name: "god_alerts_warning_count"')
    lines.append("        unique_id: god_alerts_warning_count")
    lines.append("        state: >")
    lines.append("          {% set n = namespace(c=0) %}")
    for h in hosts:
        name = h["name"]
        lines.append(
            f"          {{% set cpu = states('sensor.god_host_{name}_cpu') | float(0) %}}"
        )
        lines.append(
            f"          {{% set mem = states('sensor.god_host_{name}_mem') | float(0) %}}"
        )
        lines.append(
            f"          {{% set dk  = states('sensor.god_host_{name}_disk') | float(0) %}}"
        )
        lines.append(
            f"          {{% set tp  = states('sensor.god_host_{name}_temp') | float(0) %}}"
        )
        lines.append(
            "          {% if cpu>80 or mem>85 or dk>85 or tp>75 %}{% set n.c = n.c + 1 %}{% endif %}"
        )
    lines.append("          {{ n.c }}")

    # critical_count
    lines.append('      - name: "god_alerts_critical_count"')
    lines.append("        unique_id: god_alerts_critical_count")
    lines.append("        state: >")
    lines.append("          {% set n = namespace(c=0) %}")
    for h in hosts:
        name = h["name"]
        lines.append(
            f"          {{% set cpu = states('sensor.god_host_{name}_cpu') | float(0) %}}"
        )
        lines.append(
            f"          {{% set mem = states('sensor.god_host_{name}_mem') | float(0) %}}"
        )
        lines.append(
            f"          {{% set dk  = states('sensor.god_host_{name}_disk') | float(0) %}}"
        )
        lines.append(
            f"          {{% set tp  = states('sensor.god_host_{name}_temp') | float(0) %}}"
        )
        lines.append(
            "          {% if cpu>95 or mem>95 or dk>95 or tp>85 %}{% set n.c = n.c + 1 %}{% endif %}"
        )
    lines.append("          {{ n.c }}")

    # online_count + offline_count
    lines.append('      - name: "god_hosts_online_count"')
    lines.append("        unique_id: god_hosts_online_count")
    lines.append("        state: >")
    lines.append("          {% set n = namespace(c=0) %}")
    for h in hosts:
        name = h["name"]
        lines.append(
            f"          {{% if is_state('binary_sensor.god_host_{name}_online', 'on') %}}{{% set n.c = n.c + 1 %}}{{% endif %}}"
        )
    lines.append("          {{ n.c }}")
    lines.append('        attributes:')
    lines.append(f'          total: {len(hosts)}')

    lines.append('      - name: "god_alerts_offline_count"')
    lines.append("        unique_id: god_alerts_offline_count")
    lines.append("        state: >")
    lines.append("          {% set n = namespace(c=0) %}")
    for h in hosts:
        name = h["name"]
        lines.append(
            f"          {{% if is_state('binary_sensor.god_host_{name}_online', 'off') %}}{{% set n.c = n.c + 1 %}}{{% endif %}}"
        )
    lines.append("          {{ n.c }}")

    return "\n".join(lines) + "\n"


def main():
    hosts = load_hosts()
    if not hosts:
        print("[gen] no hosts in options.json - aborting", file=sys.stderr)
        sys.exit(0)
    os.makedirs(OUT_PKG_DIR, exist_ok=True)
    pkg = gen_package(hosts)
    with open(PKG_FILE, "w") as f:
        f.write(pkg)
    print(f"[gen] wrote {PKG_FILE} ({len(pkg)} bytes)")
    print(f"[gen] hosts: {len(hosts)}")
    print(f"[gen] sensors per host: {len(PER_HOST_METRICS) + 1} (4 metrics + online_raw)")
    print("[gen] Lovelace dashboard generation DROPPED in v0.4.0 — UI lives in webui.")


if __name__ == "__main__":
    main()
